'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8').replaceAll('\r\n','\n');
const modules=['owner-authority','normal-authority','cloud-authority','legacy-cloud-decision','authority-cloud-decision','auxiliary-progress'];

test('durability protocol suites are blocking quality gates in CI',()=>{
 const ci=read('.github/workflows/ci.yml');
 const step=ci.match(/- name: Durable chest authority, recovery and cloud contracts\n([\s\S]*?)(?=\n      - name:)/)?.[1];
 assert.ok(step,'Missing durability CI step');
 const quality=ci.split('  quality:')[1].split('  smoke-e2e:')[0];
 assert.match(quality,/working-directory: tests\/payments\n        run: npm ci --ignore-scripts/);
 assert.ok(quality.indexOf('Install embedded PostgreSQL contract dependency') < quality.indexOf('Durable chest authority, recovery and cloud contracts'));
 assert.match(step,/run: node --test isolated-authority\/\*\.test\.cjs isolated-recovery\/\*\.test\.cjs isolated-cloud\/\*\.test\.cjs/);
 assert.doesNotMatch(step,/continue-on-error|\|\|/);
});

test('release, Sentry and durability assets have coherent cache versions',()=>{
 const version=JSON.parse(read('version.json')).version;
 const sw=read('sw.js');
 assert.ok(sw.includes(`const CACHE = 'nefroquest-v${version}';`));
 for(const html of ['index.html','jogar/index.html']) assert.ok(read(html).includes(`release: 'nefroquest@${version}'`),html);
 for(const name of modules){
  const assetVersion=read('jogar/index.html').match(new RegExp('src="js/'+name+'\\.js\\?v=([0-9.]+)"'))?.[1];
  assert.ok(assetVersion,`cache-busted script ${name}`);
  assert.ok(sw.includes(`'/js/${name}.js',`),`precache ${name}`);
  assert.ok(sw.includes(`'/js/${name}.js': '${assetVersion}'`),`asset version ${name}`);
  assert.ok(fs.existsSync(path.join(root,'js',name+'.js')));
 }
});

test('release does not silently activate unverified durable/cloud gates',()=>{
 for(const file of ['index.html','jogar/index.html']){
  assert.doesNotMatch(read(file),/NQ_(?:DURABLE_PROGRESS|OWNER_CLOUD_GUARD_VERIFIED)\s*=\s*true/);
 }
});

test('audited authority core and generated browser module remain identical',()=>{
 const core=read('isolated-authority/owner-authority.cjs');
 const body=core.replace(/^'use strict';\n/,'').replace(/module\.exports=\{createAuthority\};\s*$/,'return Object.freeze({createAuthority});');
 assert.notEqual(body,core);
 const expected="// Generated by isolated-recovery/build-owner-browser.cjs. Do not edit independently.\n(function(root,factory){'use strict';const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;else root.NQOwnerAuthority=api;})(typeof window!=='undefined'?window:globalThis,function(){\n'use strict';\n"+body+"\n});\n";
 assert.equal(read('js/owner-authority.js'),expected);
});
